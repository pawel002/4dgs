#!/usr/bin/env python
"""Temporal compression for gaussian-splatting frame sequences (4D / temporal-splatfacto).

The temporal pipeline writes one ``.ply`` per video frame, all with the SAME gaussians in the
SAME order (count + colour are held constant; only motion/shape/opacity change). That means
every per-gaussian attribute is a *time series* of length F (the number of frames). Most of
these series are very smooth (positions) or constant (colour, normals), so they compress
extremely well in a frequency basis.

Method — per-attribute DCT truncation
-------------------------------------
For each scalar attribute (x, y, z, opacity, scale_*, rot_*, ...) we stack its value across all
F frames into an ``[F, N]`` array (N = #gaussians) and take the Discrete Cosine Transform along
time. The DCT (vs the plain Fourier/DFT) uses an *even extension*, so it has no artificial
wrap-around discontinuity between the last and first frame — non-periodic motion compresses with
far fewer coefficients (this is why JPEG uses the DCT). We then keep only the lowest ``K``
coefficients per attribute, where ``K`` is chosen **adaptively per attribute** to retain a target
fraction of the signal energy (``--quality``), capped at ``--max-coeffs``. Reconstruction is an
inverse DCT with the dropped (high-frequency) coefficients set to zero — i.e. a smooth low-pass
fit to each attribute's evolution, exactly the "fit a function to the parameter over the 150
frames" idea. Coefficients are stored as float16 (empirically lossless here — truncation error
dominates quantization error).

Attributes that are detected to be **constant in time** (e.g. frozen colours) are stored once per
gaussian; attributes that are **identically zero** (e.g. normals) are stored not at all.

So if a 150-frame attribute is captured by ~25 coefficients we get ~6x on that attribute; cheap
attributes (positions ~10-20, colours 1, normals 0) push the overall ratio much higher.

Round trip
----------
    # compress a directory of frame plys into a compressed directory
    python temporal_compress.py compress  <ply_dir> <compressed_dir> [--quality 0.999] [--max-coeffs 64]

    # decompress back into identically-numbered frame plys
    python temporal_compress.py decompress <compressed_dir> <ply_dir_out>

The reconstructed ``NNNNN.ply`` files use the standard nerfstudio gaussian-splat header and load
in any 3DGS viewer / ``ns-viewer``.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from scipy.fft import dct, idct

ZERO_EPS = 1e-8       # |value| below this everywhere -> treat attribute as identically zero
CONST_EPS = 1e-5      # temporal std below this for every gaussian -> constant in time


# ---------------------------------------------------------------- binary PLY I/O (all-float32)
def read_ply(path: str) -> Tuple[List[str], np.ndarray]:
    """Read a binary-little-endian, all-float32 gaussian PLY. Returns (property_names, [N, P])."""
    with open(path, "rb") as f:
        raw = f.read()
    marker = b"end_header\n"
    end = raw.index(marker) + len(marker)
    header = raw[:end].decode("ascii", "replace")
    props: List[str] = []
    count = None
    for line in header.splitlines():
        t = line.split()
        if line.startswith("element vertex"):
            count = int(t[2])
        elif line.startswith("property"):
            if t[1] != "float":
                raise ValueError(f"temporal_compress supports all-float plys only; got '{line}'")
            props.append(t[2])
    assert count is not None, "no 'element vertex' in PLY header"
    data = np.frombuffer(raw[end : end + count * len(props) * 4], dtype="<f4").reshape(count, len(props))
    return props, data.astype(np.float32)


def write_ply(path: str, props: List[str], data: np.ndarray) -> None:
    n = data.shape[0]
    header = (
        "ply\n"
        "format binary_little_endian 1.0\n"
        "comment Generated by temporal_compress.py\n"
        "comment Vertical Axis: z\n"
        f"element vertex {n}\n"
        + "".join(f"property float {p}\n" for p in props)
        + "end_header\n"
    )
    with open(path, "wb") as f:
        f.write(header.encode("ascii"))
        f.write(np.ascontiguousarray(data, dtype="<f4").tobytes())


# ---------------------------------------------------------------- coefficient selection
def choose_K(coeffs: np.ndarray, quality: float, max_coeffs: int) -> int:
    """Smallest K such that the average (over gaussians) retained DCT energy >= quality."""
    energy = coeffs**2
    cum = np.cumsum(energy, axis=0) / (energy.sum(axis=0, keepdims=True) + 1e-12)  # [F, N]
    frac = cum.mean(axis=1)  # average retained-energy curve over gaussians
    K = int(np.searchsorted(frac, quality) + 1)
    return max(1, min(K, max_coeffs, coeffs.shape[0]))


# ---------------------------------------------------------------- compress / decompress
def compress(ply_dir: str, out_dir: str, quality: float, max_coeffs: int) -> dict:
    files = sorted(glob.glob(os.path.join(ply_dir, "*.ply")))
    if not files:
        raise SystemExit(f"No .ply files found in {ply_dir}")
    props, first = read_ply(files[0])
    N = first.shape[0]
    F = len(files)

    # Stack into [F, N, P], verifying the gaussian count is constant (required for per-gaussian
    # time series; it is, by construction, for temporal-splatfacto output).
    A = np.empty((F, N, len(props)), dtype=np.float32)
    stems = []
    for t, fpath in enumerate(files):
        p, d = read_ply(fpath)
        if d.shape[0] != N or p != props:
            raise SystemExit(
                f"Frame {fpath} has a different gaussian count/layout ({d.shape[0]} vs {N}); "
                "temporal compression requires a constant set of gaussians across frames."
            )
        A[t] = d
        stems.append(Path(fpath).stem)

    os.makedirs(out_dir, exist_ok=True)
    arrays: Dict[str, np.ndarray] = {}
    per_prop = {}
    raw_bytes = A.size * 4
    for j, name in enumerate(props):
        X = A[:, :, j]  # [F, N]
        if np.abs(X).max() < ZERO_EPS:
            per_prop[name] = {"mode": "zero"}
        elif X.std(axis=0).max() < CONST_EPS:
            arrays[f"const__{name}"] = X.mean(axis=0).astype(np.float32)
            per_prop[name] = {"mode": "const"}
        else:
            C = dct(X, axis=0, norm="ortho")
            K = choose_K(C, quality, max_coeffs)
            arrays[f"coeff__{name}"] = C[:K].astype(np.float16)
            per_prop[name] = {"mode": "dct", "K": K}

    np.savez(os.path.join(out_dir, "temporal.npz"), **arrays)
    comp_bytes = os.path.getsize(os.path.join(out_dir, "temporal.npz"))
    manifest = {
        "format": "temporal-dct-v1",
        "num_frames": F,
        "num_gaussians": N,
        "properties": props,
        "frame_stems": stems,
        "quality": quality,
        "max_coeffs": max_coeffs,
        "per_property": per_prop,
        "raw_bytes": int(raw_bytes),
        "compressed_bytes": int(comp_bytes),
        "ratio": round(raw_bytes / max(1, comp_bytes), 3),
    }
    with open(os.path.join(out_dir, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)

    print(f"[compress] {F} frames x {N} gaussians x {len(props)} props")
    print(f"[compress] raw {raw_bytes/1e6:.2f} MB  ->  compressed {comp_bytes/1e6:.2f} MB"
          f"  ({manifest['ratio']}x)")
    kept = {n: v.get("K", v["mode"]) for n, v in per_prop.items()}
    print(f"[compress] per-property coeffs: {kept}")
    print(f"[compress] wrote {out_dir}/temporal.npz + manifest.json")
    return manifest


def decompress(comp_dir: str, out_dir: str) -> None:
    with open(os.path.join(comp_dir, "manifest.json")) as f:
        man = json.load(f)
    npz = np.load(os.path.join(comp_dir, "temporal.npz"))
    F, N = man["num_frames"], man["num_gaussians"]
    props = man["properties"]
    A = np.zeros((F, N, len(props)), dtype=np.float32)
    for j, name in enumerate(props):
        info = man["per_property"][name]
        if info["mode"] == "zero":
            continue
        if info["mode"] == "const":
            A[:, :, j] = npz[f"const__{name}"][None, :]
        else:
            C = np.zeros((F, N), dtype=np.float64)
            Ck = npz[f"coeff__{name}"].astype(np.float64)
            C[: Ck.shape[0]] = Ck
            A[:, :, j] = idct(C, axis=0, norm="ortho")

    os.makedirs(out_dir, exist_ok=True)
    stems = man.get("frame_stems") or [f"{i:05d}" for i in range(F)]
    for t in range(F):
        write_ply(os.path.join(out_dir, f"{stems[t]}.ply"), props, A[t])
    print(f"[decompress] wrote {F} plys to {out_dir}")


# ---------------------------------------------------------------- CLI
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("compress", help="compress a directory of frame plys")
    c.add_argument("ply_dir")
    c.add_argument("out_dir")
    c.add_argument("--quality", type=float, default=0.999,
                   help="target retained DCT energy per attribute (0-1). Higher = better/larger. "
                        "0.99~26x, 0.999~12x, 0.9999~8x on the reference data.")
    c.add_argument("--max-coeffs", type=int, default=64,
                   help="hard cap on coefficients per attribute (bounds size for noisy attributes).")
    d = sub.add_parser("decompress", help="decompress back into numbered frame plys")
    d.add_argument("comp_dir")
    d.add_argument("out_dir")
    a = ap.parse_args()
    if a.cmd == "compress":
        compress(a.ply_dir, a.out_dir, a.quality, a.max_coeffs)
    else:
        decompress(a.comp_dir, a.out_dir)


if __name__ == "__main__":
    main()
